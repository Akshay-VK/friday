// Run with Windows node.exe; every source here is generated under Windows TEMP.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { spawn, spawnSync } = require('node:child_process')
assert.equal(process.platform, 'win32')
const base = fs.mkdtempSync(path.join(os.tmpdir(), 'friday-inventory-native-'))
const root = path.join(base, 'root'), home = path.join(base, 'home'), outside = path.join(base, 'outside')
const preview = path.join(__dirname, '..', 'native', 'source-preview.exe')
const collector = path.join(__dirname, '..', 'native', 'source-inventory.exe')
const run = (bin, args) => spawnSync(bin, args, { encoding: 'utf8', maxBuffer: 16384, timeout: 6000 })
const snapshot = () => fs.readdirSync(root).sort().map(name => {
  const s = fs.lstatSync(path.join(root, name))
  return [name, s.size, s.mtimeMs, s.isSymbolicLink()]
})
async function main() {
  for (const dir of [root, home, outside, path.join(root, '.git'), path.join(root, 'nested'), path.join(root, 'flip')]) fs.mkdirSync(dir)
  fs.writeFileSync(path.join(root, '.git', 'config'), '[core]\nfixture=true')
  fs.writeFileSync(path.join(root, 'nested', 'ordinary.txt'), 'unchanged')
  fs.writeFileSync(path.join(outside, 'private.txt'), 'never read')
  fs.symlinkSync(outside, path.join(root, 'escape'), 'junction')
  fs.symlinkSync(root, path.join(root, 'cycle'), 'junction')
  const identity = JSON.parse(run(preview, ['--identity', root, home]).stdout).identity
  const before = snapshot()
  const success = run(collector, [root, home, identity])
  assert.equal(success.status, 0, success.stderr)
  assert.match(success.stdout, /^MANIFEST /m)
  assert.match(success.stdout, /^SKIP /m)
  assert.match(success.stdout, /^END entries=\d+ depth=3 bytes=\d+ clipped=0\s*$/m)
  assert.ok(!success.stdout.includes('private.txt'))
  assert.deepEqual(snapshot(), before, 'no source metadata changed')
  assert.equal(fs.readFileSync(path.join(root, '.git', 'config'), 'utf8'), '[core]\nfixture=true')
  assert.notEqual(run(collector, [root, home, '0'.repeat(16) + '-' + '0'.repeat(32)]).status, 0)
  assert.notEqual(run(collector, [root, root, identity]).status, 0)
  const held = spawn(collector, [root, home, identity, '--pause-flip'])
  await new Promise((resolve, reject) => {
    let text = ''
    held.stderr.on('data', chunk => { text += chunk; if (text.includes('READY_CHILD_LISTED')) resolve() })
    held.once('error', reject)
    held.once('close', () => reject(new Error('No child pause: ' + text)))
  })
  assert.throws(() => fs.renameSync(root, path.join(base, 'renamed-root')), 'root ancestor locked against rename')
  fs.renameSync(path.join(root, 'flip'), path.join(root, 'flip-original'))
  fs.symlinkSync(outside, path.join(root, 'flip'), 'junction')
  const swapped = await new Promise((resolve, reject) => { let out = ''; held.stdout.on('data', b => { out += b }); held.once('close', code => resolve({ code, out })); held.once('error', reject) })
  assert.equal(swapped.code, 0)
  assert.match(swapped.out, /^SKIP 0 /m)
  assert.match(swapped.out, /^END entries=\d+ depth=3 bytes=\d+ clipped=1\s*$/m, 'listed child that cannot be safely opened is partial')
  assert.ok(!swapped.out.includes('private.txt'))
  fs.rmSync(path.join(root, 'flip'))
  fs.renameSync(path.join(root, 'flip-original'), path.join(root, 'flip'))
  const vanished = spawn(collector, [root, home, identity, '--pause-flip'])
  await new Promise((resolve, reject) => {
    let text = ''
    vanished.stderr.on('data', chunk => { text += chunk; if (text.includes('READY_CHILD_LISTED')) resolve() })
    vanished.once('error', reject)
    vanished.once('close', () => reject(new Error('No child pause: ' + text)))
  })
  fs.renameSync(path.join(root, 'flip'), path.join(root, 'flip-original'))
  const missing = await new Promise((resolve, reject) => { let out = ''; vanished.stdout.on('data', b => { out += b }); vanished.once('close', code => resolve({ code, out })); vanished.once('error', reject) })
  assert.equal(missing.code, 0)
  assert.match(missing.out, /^SKIP 0 /m)
  assert.match(missing.out, /^END entries=\d+ depth=3 bytes=\d+ clipped=1\s*$/m)
  fs.renameSync(path.join(root, 'flip-original'), path.join(root, 'flip'))
  for (let i = 0; i < 32; i++) fs.writeFileSync(path.join(root, `long-${i.toString().padStart(2, '0')}-${'z'.repeat(100)}`), '')
  const capped = run(collector, [root, home, identity])
  assert.equal(capped.status, 0, capped.stderr)
  assert.ok(Buffer.byteLength(capped.stdout) <= 8192)
  assert.match(capped.stdout, /^END entries=\d+ depth=3 bytes=\d+ clipped=1\s*$/m)
  console.log('PASS Windows TEMP nested read, swap, root lock, stale identity, long-name output cap, no source writes')
}
main().finally(() => fs.rmSync(base, { recursive: true, force: true })).catch(e => { console.error(e); process.exitCode = 1 })
